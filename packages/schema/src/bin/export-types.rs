fn export<T: NamedType>(output: &mut String) {
    let config = ts::ExportConfiguration::new().bigint(ts::BigIntExportBehavior::Number);
    output.push_str(&ts::export::<T>(&config).expect("export Specta type"));
    output.push_str("\n\n");
}

// Specta 1.0.5 renders zero-field structs as invalid `Type<> = null` declarations.
fn export_empty(name: &str, output: &mut String) {
    output.push_str(&format!("export type {name} = Record<string, never>\n\n"));
}

fn export_operation_metadata(output: &mut String) {
    output.push_str("export type OperationResource =\n");
    for resource in OPERATION_RESOURCES {
        output.push_str(&format!("  | {:?}\n", resource.name()));
    }
    output.push('\n');
    output.push_str(
        "export type OperationMetadata = {\n  queries?: readonly OperationResource[];\n  fetches?: readonly OperationResource[];\n  mutates?: readonly OperationResource[];\n  senders: readonly KeyScope[];\n  recipients: readonly KeyScope[];\n}\n\n",
    );
    output.push_str("export const operationMetadata = {\n");
    for definition in Operation::definitions() {
        output.push_str(&format!("  {}: {{", definition.name));
        if !definition.metadata.queries.is_empty() {
            output.push_str(" queries: [");
            for (index, resource) in definition.metadata.queries.iter().enumerate() {
                if index > 0 {
                    output.push_str(", ");
                }
                output.push_str(&format!("{:?}", resource.name()));
            }
            output.push_str("],");
        }
        if !definition.metadata.fetches.is_empty() {
            output.push_str(" fetches: [");
            for (index, resource) in definition.metadata.fetches.iter().enumerate() {
                if index > 0 {
                    output.push_str(", ");
                }
                output.push_str(&format!("{:?}", resource.name()));
            }
            output.push_str("],");
        }
        if !definition.metadata.mutates.is_empty() {
            output.push_str(" mutates: [");
            for (index, resource) in definition.metadata.mutates.iter().enumerate() {
                if index > 0 {
                    output.push_str(", ");
                }
                output.push_str(&format!("{:?}", resource.name()));
            }
            output.push_str("],");
        }
        output.push_str(" senders: [");
        for (index, scope) in definition.metadata.senders.iter().enumerate() {
            if index > 0 {
                output.push_str(", ");
            }
            output.push_str(&format!("{:?}", scope_name(*scope)));
        }
        output.push_str("],");
        output.push_str(" recipients: [");
        for (index, scope) in definition.metadata.recipients.iter().enumerate() {
            if index > 0 {
                output.push_str(", ");
            }
            output.push_str(&format!("{:?}", scope_name(*scope)));
        }
        output.push_str("],");
        output.push_str(" },\n");
    }
    output.push_str("} as const satisfies Record<Operation['op'], OperationMetadata>\n\n");
}

fn scope_name(scope: KeyScope) -> &'static str {
    match scope {
        KeyScope::CoreUntrusted => "core_untrusted",
        KeyScope::Core => "core",
        KeyScope::App => "app",
        KeyScope::Passkey => "passkey",
        KeyScope::NativeUi => "native_ui",
    }
}
