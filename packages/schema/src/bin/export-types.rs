use std::{env, fs, path::PathBuf};

use keeless_schema::*;
use specta::{NamedType, ts};

fn main() {
    let generated = generate();
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("index.d.ts");

    if env::args().any(|arg| arg == "--check") {
        let checked = fs::read_to_string(&path).expect("read checked TypeScript declarations");
        assert_eq!(checked, generated, "index.d.ts is stale; run the exporter");
    } else {
        fs::write(path, generated).expect("write TypeScript declarations");
    }
}

fn generate() -> String {
    let mut output =
        String::from("// Generated by `cargo run --bin export-types`. Do not edit.\n\n");
    export_message_frame(&mut output);
    export::<StorageDescriptor>(&mut output);
    export::<DatabaseStatus>(&mut output);
    export::<KeelessConfig>(&mut output);
    export::<KeelessConfigPatch>(&mut output);
    export::<DatabaseNodeId>(&mut output);
    export::<IconReference>(&mut output);
    export::<EntrySummary>(&mut output);
    export::<CustomIcon>(&mut output);
    export::<GroupHierarchyItem>(&mut output);
    export::<TagSummary>(&mut output);
    export::<EntryFieldKind>(&mut output);
    export::<EntryFieldInformation>(&mut output);
    export::<EntryAttachmentInformation>(&mut output);
    export::<OpenArgs>(&mut output);
    export::<CreateArgs>(&mut output);
    export::<UnlockArgs>(&mut output);
    export_empty("LockArgs", &mut output);
    export_empty("GetDatabaseStatusArgs", &mut output);
    export_empty("GetStorageDescriptorArgs", &mut output);
    export_empty("GetConfigArgs", &mut output);
    export::<SetConfigArgs>(&mut output);
    export::<GetEntriesArgs>(&mut output);
    export_empty("GetGroupHierarchyArgs", &mut output);
    export::<GetGroupEntriesArgs>(&mut output);
    export::<GetTagEntriesArgs>(&mut output);
    export_empty("GetTrashEntriesArgs", &mut output);
    export_empty("GetTagsArgs", &mut output);
    export::<GetEntryDetailArgs>(&mut output);
    export::<EntryFieldUpdate>(&mut output);
    export::<UpdateEntryArgs>(&mut output);
    export::<DeleteEntryArgs>(&mut output);
    export::<SaveDatabaseArgs>(&mut output);
    export_empty("GetCustomIconsArgs", &mut output);
    export_empty("GetEntryTemplatesArgs", &mut output);
    export::<MoveGroupArgs>(&mut output);
    export::<MoveEntryArgs>(&mut output);
    export::<AddEntryArgs>(&mut output);
    export::<AddEntryFromTemplateArgs>(&mut output);
    export::<AddGroupArgs>(&mut output);
    export::<DeleteGroupArgs>(&mut output);
    export::<RenameGroupArgs>(&mut output);
    export::<RevealEntryFieldArgs>(&mut output);
    export::<Operation>(&mut output);
    export::<OperationRequest>(&mut output);
    export_empty("EmptyResult", &mut output);
    export::<DatabaseStatusResult>(&mut output);
    export::<StorageDescriptorResult>(&mut output);
    export::<ConfigResult>(&mut output);
    export::<EntriesResult>(&mut output);
    export::<GroupHierarchyResult>(&mut output);
    export::<TagsResult>(&mut output);
    export::<EntryDetailResult>(&mut output);
    export::<CustomIconsResult>(&mut output);
    export::<AddEntryResult>(&mut output);
    export::<AddGroupResult>(&mut output);
    export::<RevealEntryFieldResult>(&mut output);
    export::<OperationSuccess>(&mut output);
    export::<OperationError>(&mut output);
    output.push_str(
        "export type OperationOutcome = ({ status: \"success\" } & OperationSuccess) | { status: \"error\"; error: OperationError }\n\n",
    );
    output.push_str("export type OperationResponse = OperationOutcome & { requestId: string }\n\n");
    output
}

fn export<T: NamedType>(output: &mut String) {
    let config = ts::ExportConfiguration::new().bigint(ts::BigIntExportBehavior::Number);
    output.push_str(&ts::export::<T>(&config).expect("export Specta type"));
    output.push_str("\n\n");
}

fn export_message_frame(output: &mut String) {
    let config = ts::ExportConfiguration::new().bigint(ts::BigIntExportBehavior::Number);
    let declaration = ts::export::<MessageFrame>(&config)
        .expect("export Specta type")
        .replacen("version: number", "version: 1", 1);
    output.push_str(&declaration);
    output.push_str("\n\n");
}

// Specta 1.0.5 renders zero-field structs as invalid `Type<> = null` declarations.
fn export_empty(name: &str, output: &mut String) {
    output.push_str(&format!("export type {name} = Record<string, never>\n\n"));
}
